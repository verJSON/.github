#!/usr/bin/env python3
"""Generated callers move by regeneration; their action pins move in the generators.

Renovate edited action pins inside adopters' generated `release.yml`
(Verjson/verjson-agents#419, #420, #421), which breaks the adopter's
byte-faithfulness test and recurs after every repin (#1812). The cure has two
halves that must stay complete as the generators grow:

* the generators' own pins are Renovate-managed here, through a regex custom
  manager in `renovate.json`, grouped with this repository's workflow digests;
* adopters fence the generated caller paths through the organization preset,
  which extends `renovate/generated-callers.json` from this repository.
"""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[2]
RENOVATE = ROOT / "renovate.json"
CHANGELOG_GENERATOR = ROOT / "scripts/gen-changelog-caller.sh"
PIN_DECLARATION = re.compile(
    r"^release_[a-z_]+='(?P<uses>[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_./-]+)?)"
    r"@(?P<sha>[0-9a-f]{40}) # (?P<tag>v[0-9][0-9A-Za-z.+-]*)'$",
    re.MULTILINE,
)
THIRD_PARTY_PIN = re.compile(
    r"(?P<owner>[A-Za-z0-9_.-]+)/[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_./-]+)?@[0-9a-f]{40}\b"
)
# Pins Renovate cannot read, each with the reason it is not moved here.
UNMANAGED_GENERATOR_PINS = {
    (
        "scripts/gen-node-required-workflow.py",
        "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1",
    ): (
        "It renders this repository's CLI Projects required workflow (ADR 0212), whose "
        "checkout pins carry no version comment, so the github-actions manager skips "
        "them as unversioned-reference and nothing edits them behind the generator. "
        "Making them movable means giving them a comment, which changes the rendered "
        "required workflow and is follow-up work."
    ),
}


# Workflows another repository accepts by exact content digest. Their pins move
# only together with that consumer, never as a side effect of a generator bump.
EXACT_DIGEST_WORKFLOWS = {
    ".github/workflows/runner-canary.yml": (
        "scripts/runner-canary-contract.test.py pins its SHA-256, and "
        "verjson-cli-cloud contracts/workflows/runner-canary.yml and "
        "src/cloud/runner-promotion.ts pin the published bytes and the receipt's "
        "uploadArtifactCommit."
    ),
}
USES_LINE = re.compile(
    r"^\s*(?:-\s+)?uses:\s*['\"]?(?P<uses>[A-Za-z0-9_.-]+/[A-Za-z0-9_./-]+)@(?P<sha>[0-9a-f]{40})",
    re.MULTILINE,
)
GENERATED_CALLER_HEADER = re.compile(
    r"^# Generated by verJSON/\.github scripts/gen-[a-z0-9-]+\.sh ", re.MULTILINE | re.IGNORECASE
)


def workflow_and_action_files() -> list[Path]:
    return sorted(
        path
        for directory in (ROOT / ".github/workflows", ROOT / ".github/actions")
        for pattern in ("*.yml", "*.yaml")
        for path in directory.rglob(pattern)
        if path.is_file()
    )


RELEASE_MODES = {
    "release-node": (),
    "release-snapshot": (),
    "release-artifact": ("--build-runner", "ubuntu-24.04"),
}


def generate(generator: str, mode: str, ref: str, *arguments: str) -> str:
    """Run generator text exactly as release-verify.sh runs a pinned one."""
    # `bash -s` makes $0 "bash", so the generator's `$(dirname "$0")/..` lookups
    # resolve against this cwd's parent: the repository that holds `ref`.
    result = subprocess.run(
        ["bash", "-s", mode, ref, *arguments],
        input=generator, cwd=ROOT / "scripts",
        check=False, capture_output=True, text=True,
    )
    if result.returncode != 0:
        raise AssertionError(f"{mode} generation failed: {result.stderr}")
    return result.stdout


def extract_heredoc(text: str, delimiter: str) -> str:
    match = re.search(
        rf"<<'{delimiter}'\n(?P<body>.*?)\n{delimiter}\n", text, re.DOTALL
    )
    if match is None:
        raise AssertionError(f"the generated contract test lost its {delimiter} block")
    return match["body"] + "\n"


def contract_test_constant(text: str, name: str) -> str:
    match = re.search(rf"^{name}='(?P<value>[^']*)'$", text, re.MULTILINE)
    if match is None:
        raise AssertionError(f"the generated contract test does not declare {name}")
    return match["value"]


def renovate_pattern(pattern: str) -> re.Pattern[str]:
    """Translate Renovate's RE2 named groups to Python's spelling."""
    return re.compile(pattern.replace("(?<", "(?P<"))


def manager_file_matches(manager: dict, relative_path: str) -> bool:
    for pattern in manager.get("managerFilePatterns", []):
        if not (pattern.startswith("/") and pattern.endswith("/")):
            raise AssertionError(f"managerFilePatterns entry {pattern!r} must be a regex")
        if re.search(pattern[1:-1].replace("\\/", "/"), relative_path):
            return True
    return False


def generator_pin_managers(config: dict) -> list[dict]:
    return [
        manager
        for manager in config.get("customManagers", [])
        if manager.get("customType") == "regex"
        and manager_file_matches(manager, "scripts/gen-changelog-caller.sh")
    ]


class GeneratorPinManager(unittest.TestCase):
    def setUp(self) -> None:
        self.config = json.loads(RENOVATE.read_text(encoding="utf-8"))
        self.generator = CHANGELOG_GENERATOR.read_text(encoding="utf-8")

    def test_one_custom_manager_reads_every_generator_pin_declaration(self) -> None:
        managers = generator_pin_managers(self.config)
        self.assertEqual(len(managers), 1, "one regex manager must own the generator pins")
        manager = managers[0]
        self.assertEqual(manager.get("datasourceTemplate"), "github-tags")
        # The github-actions manager's own versioning, so a `# v7` floating tag
        # keeps its precision and only the digest moves, exactly as it does in
        # this repository's workflows.
        self.assertEqual(manager.get("versioningTemplate"), "github-actions")

        declared = [
            (match["uses"], match["sha"], match["tag"])
            for match in PIN_DECLARATION.finditer(self.generator)
        ]
        self.assertGreaterEqual(len(declared), 6, "the release pin declarations moved")
        extracted = []
        for pattern in manager.get("matchStrings", []):
            for match in renovate_pattern(pattern).finditer(self.generator):
                extracted.append((match["depName"], match["currentDigest"], match["currentValue"]))
        expected = [
            (uses if uses.count("/") == 1 else "/".join(uses.split("/")[:2]), sha, tag)
            for uses, sha, tag in declared
        ]
        self.assertEqual(sorted(extracted), sorted(expected))

    def test_no_generator_carries_a_pin_the_manager_cannot_move(self) -> None:
        # A second spelling of a declared pin is the copy Renovate leaves behind:
        # its PR would then fail this repository's own contract test, and the
        # generator would stop moving at all.
        manager = generator_pin_managers(self.config)[0]
        patterns = [renovate_pattern(pattern) for pattern in manager["matchStrings"]]
        unmanaged = []
        for generator in sorted((ROOT / "scripts").glob("gen-*")):
            relative = generator.relative_to(ROOT).as_posix()
            if not manager_file_matches(manager, relative):
                continue
            text = generator.read_text(encoding="utf-8")
            spans = [
                match.span()
                for pattern in patterns
                for match in pattern.finditer(text)
            ]
            for match in THIRD_PARTY_PIN.finditer(text):
                if match["owner"].casefold() == "verjson":
                    continue
                if any(start <= match.start() and match.end() <= end for start, end in spans):
                    continue
                line = text.count("\n", 0, match.start()) + 1
                if (relative, match.group(0)) in UNMANAGED_GENERATOR_PINS:
                    continue
                unmanaged.append(f"{relative}:{line}: {match.group(0)}")
        self.assertEqual(unmanaged, [])

    def test_a_renovated_generator_still_passes_its_release_shape_contract(self) -> None:
        # The PR Renovate opens must be mergeable: the generated contract may
        # compare action pins only to the declarations Renovate moved, never to
        # a digest or literal frozen beside them.
        manager = generator_pin_managers(self.config)[0]
        renovated = self.generator
        moved = 0
        for pattern in (renovate_pattern(value) for value in manager["matchStrings"]):
            def bump(match: re.Match[str]) -> str:
                nonlocal moved
                moved += 1
                new_digest = hashlib.sha1(f"renovated:{match['depName']}".encode()).hexdigest()
                return match.group(0).replace(match["currentDigest"], new_digest)
            renovated = pattern.sub(bump, renovated)
        self.assertGreaterEqual(moved, 6)
        self.assertNotEqual(renovated, self.generator)

        ref = subprocess.run(
            ["git", "-C", str(ROOT), "rev-parse", "HEAD"],
            check=True, capture_output=True, text=True,
        ).stdout.strip()
        contract_test = generate(renovated, "contract-test", ref)
        release_shape = extract_heredoc(contract_test, "RELEASE_SHAPE_PY")
        environment = {
            "PATH": os.environ["PATH"],
            "CONTRACT_REF": ref,
            "RELEASE_CALLER_PACKAGE_DIRS_JSON": '["."]',
            **{
                name: contract_test_constant(contract_test, name)
                for name in ("EXPECTED_RELEASE_CHECKOUT", "EXPECTED_RELEASE_SETUP_NODE")
            },
        }
        with tempfile.TemporaryDirectory() as scratch:
            checker = Path(scratch) / "release-shape.py"
            checker.write_text(release_shape, encoding="utf-8")
            for mode, arguments in RELEASE_MODES.items():
                workflow = Path(scratch) / f"{mode}.yml"
                workflow.write_text(generate(renovated, mode, ref, *arguments), encoding="utf-8")
                result = subprocess.run(
                    ["python3", "-I", str(checker), str(workflow)],
                    env=environment, capture_output=True, text=True,
                )
                self.assertEqual(result.returncode, 0, f"{mode}: {result.stderr}")

    def test_generator_pins_match_this_repository_workflow_pins(self) -> None:
        # One audited commit per action: the generator declares the commit this
        # repository runs everywhere else, and Renovate's grouped PR moves both.
        # Generated callers here follow their own contract pin, so they are
        # compared only by regeneration (scripts/release-verify.sh).
        declared = {
            match["uses"]: match["sha"]
            for match in PIN_DECLARATION.finditer(self.generator)
        }
        divergent = []
        for path in workflow_and_action_files():
            text = path.read_text(encoding="utf-8")
            if GENERATED_CALLER_HEADER.search(text):
                continue
            if path.relative_to(ROOT).as_posix() in EXACT_DIGEST_WORKFLOWS:
                continue
            for match in USES_LINE.finditer(text):
                sha = declared.get(match["uses"])
                if sha is not None and match["sha"] != sha:
                    line = text.count("\n", 0, match.start()) + 1
                    divergent.append(
                        f"{path.relative_to(ROOT)}:{line}: {match['uses']}@{match['sha']} "
                        f"(generator declares {sha})"
                    )
        self.assertEqual(divergent, [])

    def test_every_recorded_unmanaged_pin_still_exists(self) -> None:
        for relative, pin in UNMANAGED_GENERATOR_PINS:
            self.assertIn(pin, (ROOT / relative).read_text(encoding="utf-8"), relative)

    def test_every_exact_digest_exception_still_names_a_workflow(self) -> None:
        for relative in EXACT_DIGEST_WORKFLOWS:
            self.assertTrue((ROOT / relative).is_file(), relative)


if __name__ == "__main__":
    unittest.main(verbosity=2)
