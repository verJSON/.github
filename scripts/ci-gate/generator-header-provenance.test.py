#!/usr/bin/env python3
"""A generated header must be enough to regenerate its file byte for byte.

Every `gen-changelog-caller.sh` mode stamps `# Generated by verJSON/.github
scripts/gen-changelog-caller.sh <mode> <sha> [options]`. An adopter repairing or
re-pinning a member reads that line to learn how it was made, so an option that
changed the output and is missing from the header is lost at the next
regeneration: verjson-cli's `--release-caller-package-dirs` and verjson-cli-cloud's
`--node-version 24.18.0` contract tests both regenerated to different bytes from
their headers alone.

For each mode, this generates the file with every option the mode accepts, reads
the options back out of the header, regenerates from them alone and requires the
same bytes. The mode list is read from the generator's own usage line, so a new
mode without a case here fails rather than going unchecked.
"""
from __future__ import annotations

import pathlib
import re
import shlex
import subprocess
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[2]
GENERATOR = ROOT / "scripts/gen-changelog-caller.sh"
HEADER = re.compile(
    r"^# Generated by verJSON/\.github scripts/gen-changelog-caller\.sh "
    r"(?P<command>[a-z][a-z-]* [0-9a-f]{40}(?: .*)?)$",
    re.MULTILINE,
)
MACOS_LANE = "${{ fromJSON(vars.CI_LANE_TRUSTED_MACOS) }}"

# Every option a mode accepts, at a non-default value, so each one has to reach
# the header to survive a regeneration. Modes that accept several mutually
# exclusive option shapes get one case per shape.
CASES: dict[str, list[list[str]]] = {
    "workflow": [[]],
    "generated-artifacts": [[]],
    "generated-artifacts-with-adr-index": [[]],
    "renovate-attribution": [[]],
    "adr-index-generator": [[]],
    "adr-index-test": [[]],
    "renderer": [[]],
    "contract-test": [
        # verjson-cli: a second release caller with its own package directories.
        ["--release-caller-package-dirs", ".github/workflows/release-cli.yml=packages/cli,packages/core"],
        # verjson-cli-cloud: a patch-pinned Node version.
        ["--node-version", "24.18.0"],
        ["--scope", "@acme", "--package-dir", "packages/a", "--release-asset", "dist/a.tgz",
         "--release-asset", "dist/b.tgz"],
        ["--only-package-dir", "packages/a", "--only-package-dir", "packages/b"],
        ["--build-runner", "ubuntu-24.04-arm", "--build-runner", MACOS_LANE,
         "--approved-internal-package", "@verjson/cli-cloud"],
    ],
    "pr-gate": [["--untrusted-runner", "self-hosted,linux"]],
    "release-node": [
        ["--scope", "@acme", "--node-version", "22.1", "--default-prefix", "cli-v",
         "--default-component", "cli", "--package-dir", "packages/a", "--release-asset", "dist/a.tgz"],
        ["--only-package-dir", "packages/a"],
    ],
    "release-artifact": [
        ["--build-runner", "ubuntu-24.04-arm", "--build-runner", MACOS_LANE,
         "--approved-internal-package", "@verjson/cli-cloud", "--scope", "@acme",
         "--node-version", "22", "--default-prefix", "cli-v", "--default-component", "cli",
         "--package-dir", "packages/a"],
    ],
    "release-snapshot": [
        ["--scope", "@acme", "--node-version", "22", "--default-prefix", "cli-v",
         "--default-component", "cli", "--only-package-dir", "packages/a"],
    ],
    "release-propose": [["--autonomy", "propose"], ["--autonomy", "dispatch"]],
}
# Byte-embedded and independent of the ref and of every option; its comment names
# no commit, so there is no header to read back.
HEADERLESS = {"codeowners"}


def head_commit() -> str:
    return subprocess.run(
        ["git", "-C", str(ROOT), "rev-parse", "HEAD"],
        check=True, capture_output=True, text=True,
    ).stdout.strip()


def generate(arguments: list[str]) -> bytes:
    result = subprocess.run(
        ["bash", str(GENERATOR), *arguments], cwd=ROOT, capture_output=True, check=False,
    )
    if result.returncode != 0:
        raise AssertionError(
            f"generator refused {shlex.join(arguments)}: {result.stderr.decode(errors='replace')}"
        )
    return result.stdout


def usage_modes() -> set[str]:
    result = subprocess.run(["bash", str(GENERATOR)], capture_output=True, text=True, check=False)
    match = re.search(r"\{([a-z|-]+)\} <40-hex-commit>", result.stderr)
    if match is None:
        raise AssertionError("generator usage no longer lists its modes")
    return set(match.group(1).split("|"))


class HeaderRegeneratesItsFile(unittest.TestCase):
    def test_every_mode_is_covered(self):
        self.assertEqual(usage_modes(), set(CASES) | HEADERLESS)

    def test_the_header_alone_reproduces_every_mode_byte_for_byte(self):
        ref = head_commit()
        for mode, option_sets in CASES.items():
            for options in option_sets:
                with self.subTest(mode=mode, options=shlex.join(options)):
                    original = generate([mode, ref, *options])
                    headers = HEADER.findall(original.decode())
                    self.assertEqual(1, len(headers), f"{mode} must stamp exactly one header")
                    recorded = shlex.split(headers[0])
                    self.assertEqual([mode, ref], recorded[:2])
                    self.assertEqual(original, generate(recorded))

    def test_a_default_invocation_keeps_its_bare_header(self):
        # Adopters regenerated without options must see no byte change from this fix.
        ref = head_commit()
        for mode in ("contract-test", "pr-gate", "release-node", "release-snapshot"):
            with self.subTest(mode=mode):
                header = HEADER.search(generate([mode, ref]).decode())
                self.assertEqual(f"{mode} {ref}", header.group("command"))


class GeneratedContractTestAdmitsRecordedOptions(unittest.TestCase):
    """The adopter's contract test reads the PR gate's header; a recorded option must not fail it."""

    def pr_gate_pattern(self, ref: str) -> str:
        suite = generate(["contract-test", ref]).decode()
        lines = [line for line in suite.splitlines()
                 if "gen-changelog-caller\\.sh pr-gate" in line and "grep -qE" in line]
        self.assertEqual(1, len(lines), "the contract test must check the PR gate header once")
        pattern = re.search(r'grep -qE "(?P<pattern>[^"]+)"', lines[0]).group("pattern")
        return pattern.replace("$CONTRACT_REF", ref)

    def header_matches(self, pattern: str, header: str) -> bool:
        return subprocess.run(["grep", "-qE", pattern], input=header + "\n",
                              text=True, check=False).returncode == 0

    def test_the_pr_gate_header_check_accepts_exactly_what_pr_gate_stamps(self):
        ref = head_commit()
        pattern = self.pr_gate_pattern(ref)
        for options in ([], ["--untrusted-runner", "self-hosted,untrusted-pr,ephemeral"]):
            with self.subTest(options=options):
                header = HEADER.search(generate(["pr-gate", ref, *options]).decode()).group(0)
                self.assertTrue(self.header_matches(pattern, header), header)
        prefix = f"# Generated by verJSON/.github scripts/gen-changelog-caller.sh pr-gate {ref}"
        for forged in (f"{prefix} --scope @acme", f"{prefix} --untrusted-runner",
                       f"{prefix} --untrusted-runner Self-Hosted", f"{prefix}x",
                       prefix.replace(ref, "f" * 40)):
            with self.subTest(forged=forged):
                self.assertFalse(self.header_matches(pattern, forged))


if __name__ == "__main__":
    unittest.main()
