#!/usr/bin/env bash
# Behavioral tests for scripts/release-verify.sh, this repository's own release
# verification hook (verJSON/.github#1758).
#
# The hook refuses a release whose .github/workflows/release.yml is not exactly
# what its pinned generator emits. It runs only inside a dispatched release, so
# nothing else exercised it: after #1702 changed the generated header spelling,
# the hook matched no header and would have failed every self-release. Each case
# runs the real hook in a disposable repository whose pin commit carries the
# real generator, with the later verification commands stubbed out.
set -uo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
repo_root="$(cd "$here/.." && pwd)"
hook="$repo_root/scripts/release-verify.sh"
generator="$repo_root/scripts/gen-changelog-caller.sh"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
fails=0
pass() { printf 'ok   - %s\n' "$1"; }
fail() { printf 'FAIL - %s\n' "$1"; fails=$((fails + 1)); }

# Stub the verification commands that follow the pin check; the pin check is
# the behavior under test, and each stub records that it was reached.
mkdir -p "$tmp/bin"
printf '%s\n' '#!/usr/bin/env bash' 'echo "node $*" >>"$STUB_LOG"' >"$tmp/bin/node"
# The hook pipes the pinned generator into `bash -s`, so the generator's own
# local-object lookup misses and it fetches the pinned engine over the network
# to digest it. Serve that fetch from the fixture's pin commit instead.
cat >"$tmp/bin/curl" <<'STUB'
#!/usr/bin/env bash
url="${*: -1}"
[[ "$url" =~ ^https://raw\.githubusercontent\.com/verJSON/\.github/([0-9a-f]{40})/scripts/changelog\.py$ ]] || exit 22
echo "curl $url" >>"$STUB_LOG"
git -C "$FIXTURE_REPO" show "${BASH_REMATCH[1]}:scripts/changelog.py"
STUB
chmod +x "$tmp/bin/node" "$tmp/bin/curl"

# fixture <name> -> a repository whose first commit carries the generator and
# whose second commit carries the generated release caller pinned to the first.
fixture() {
  local dir="$tmp/$1" pin
  mkdir -p "$dir/scripts/ci-gate" "$dir/.github/workflows"
  git init -q "$dir"
  git -C "$dir" config user.email test@example.invalid
  git -C "$dir" config user.name test
  cp "$generator" "$dir/scripts/gen-changelog-caller.sh"
  cp "$repo_root/scripts/changelog.py" "$dir/scripts/changelog.py"
  git -C "$dir" add scripts/gen-changelog-caller.sh scripts/changelog.py
  git -C "$dir" commit -qm generator
  pin="$(git -C "$dir" rev-parse HEAD)"
  bash "$dir/scripts/gen-changelog-caller.sh" release-node "$pin" --only-package-dir . \
    >"$dir/.github/workflows/release.yml" || return 1
  cp "$hook" "$dir/scripts/release-verify.sh"
  printf '%s\n' 'import sys' 'sys.exit(0)' >"$dir/scripts/changelog.py"
  printf '%s\n' 'import sys' 'sys.exit(0)' >"$dir/scripts/adr-relative-links.test.py"
  for stub in render-next.sh gen-adr-index.sh doc-fragment-names.test.sh; do
    printf '%s\n' '#!/usr/bin/env bash' "echo \"$stub \$*\" >>\"\$STUB_LOG\"" >"$dir/scripts/$stub"
  done
  git -C "$dir" add -A
  git -C "$dir" commit -qm caller
  printf '%s' "$dir"
}

# verify <dir> [env...] -> runs the hook; output in $tmp/out, status returned.
verify() {
  local dir="$1"
  shift
  : >"$tmp/stub.log"
  env PATH="$tmp/bin:$PATH" STUB_LOG="$tmp/stub.log" FIXTURE_REPO="$dir" PACKAGE_VERSION=0.0.0-test "$@" \
    bash "$dir/scripts/release-verify.sh" >"$tmp/out" 2>&1
}

dir="$(fixture generated)" || { echo "FAIL - cannot build the generated fixture"; exit 1; }
if verify "$dir"; then
  grep -qx 'release verification passed' "$tmp/out" \
    && grep -q '^node --test scripts/ci-gate/contract-tools-package.test.js$' "$tmp/stub.log" \
    && pass "a release caller matching its pinned generator passes the pin check" \
    || fail "the hook exited 0 without running its verification: $(cat "$tmp/out")"
else
  fail "a release caller matching its pinned generator was refused: $(cat "$tmp/out")"
fi

# expect_refusal <name> <status> <message> -> the hook refuses $dir with that
# exit status and message, before any verification command runs.
expect_refusal() {
  local name="$1" expected_status="$2" message="$3" status=0
  verify "$dir" "${@:4}" || status=$?
  if [ "$status" -ne "$expected_status" ]; then
    fail "$name: exited $status, expected $expected_status: $(cat "$tmp/out")"
  elif ! grep -qF "$message" "$tmp/out"; then
    fail "$name: refused for another reason: $(cat "$tmp/out")"
  elif grep -q '^node ' "$tmp/stub.log"; then
    fail "$name: verification ran after the refusal"
  else
    pass "$name"
  fi
}

generated_caller="$(cat "$dir/.github/workflows/release.yml")"

printf '%s\n# hand edit\n' "$generated_caller" >"$dir/.github/workflows/release.yml"
expect_refusal "a hand-edited release caller is refused" 1 \
  ".github/workflows/release.yml differs from its pinned generator"

printf '%s\n' "$generated_caller" \
  | sed 's|^# Generated by verJSON/\.github |# Generated by Verjson/.github |' \
  >"$dir/.github/workflows/release.yml"
expect_refusal "a header in the retired organization spelling is refused" 1 \
  ".github/workflows/release.yml carries no package-release pin header"

printf '%s\n' "$generated_caller" >"$dir/.github/workflows/release.yml"
expect_refusal "a run with an empty dispatched version is refused" 2 \
  "PACKAGE_VERSION must be set by the dispatched contract release" PACKAGE_VERSION=

printf '%s\n' '#!/usr/bin/env bash' 'echo "node $*" >>"$STUB_LOG"' 'exit 7' >"$tmp/bin/node"
status=0
verify "$dir" || status=$?
if [ "$status" -eq 7 ] && ! grep -q 'release verification passed' "$tmp/out"; then
  pass "a failing verification command fails the hook with its status"
else
  fail "a failing verification command exited $status: $(cat "$tmp/out")"
fi

if [ "$fails" -gt 0 ]; then
  echo "$fails failure(s)"
  exit 1
fi
echo "release-verify: all cases passed"
